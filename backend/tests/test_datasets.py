def test_no_real_personal_data_markers_in_the_estate(out: Path) -> None:
    """Hosts, e-mail addresses and phone numbers in the estate are fictional or reserved."""
    pattern = re.compile(r"[A-Za-z0-9._%+-]+@([A-Za-z0-9.-]+\.[A-Za-z]{2,})")
    allowed = ("example", "sentry.io")
    for path in (out / "estate").rglob("*"):
        if path.suffix in {".har", ".json", ".md", ".html", ".js"}:
            for domain in pattern.findall(path.read_text(encoding="utf-8")):
                assert domain.endswith(allowed) or domain.split(".")[-1] == "example", (
                    path.name,
                    domain,
                )


