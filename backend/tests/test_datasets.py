def vendor_for(host: str, registry: list[dict[str, Any]]) -> dict[str, Any] | None:
    return next(
        (v for v in registry if host == v["pattern"] or host.endswith("." + v["pattern"])), None
    )


def test_vendor_registry_resolves_third_party_hosts(out: Path) -> None:
    registry_doc = yaml.safe_load(
        (DATASETS / "regulation/vendor_registry.yaml").read_text(encoding="utf-8")
    )
    registry, first_party = registry_doc["vendors"], registry_doc["first_party"]
    for system_id in SYSTEM_IDS:
        for recipient in truth(out, system_id)["recipients"]:
            for host in recipient["hosts"]:
                if recipient["internal"]:
                    assert any(host == d or host.endswith("." + d) for d in first_party), host
                    continue
                vendor = vendor_for(host, registry)
                assert vendor, f"{host} missing from vendor_registry.yaml"
                assert vendor["country"] == recipient["country"], host
                assert vendor["role"] == recipient["role"], host
                assert vendor["vendor"] == recipient["vendor"], host


