def derived_findings(out: Path) -> set[tuple[str, str, str | None]]:
    """What a correct rule engine would report, computed from ground truth and questionnaires."""
    # Adequacy that needs no further check; the US covers only certified organisations.
    adequate = {
        c["code"]
        for c in yaml.safe_load((DATASETS / "regulation/adequacy_countries.yaml").read_text())[
            "adequacy"
        ]
        if not c.get("requires_certification_check")
    }
    found: set[tuple[str, str, str | None]] = set()
    for system_id in SYSTEM_IDS:
        gt, q = truth(out, system_id), questionnaire(out, system_id)
        agreements = set(q["processors_with_agreement"])
        for e in gt["data_elements"]:
            if not e["declared_in_policy"]:
                found.add((system_id, "element_not_in_policy", e["id"]))
        for r in gt["recipients"]:
            if not r["internal"] and not (
                r["declared_in_policy"] and r["declared_in_questionnaire"]
            ):
                found.add((system_id, "undeclared_recipient", r["id"]))
            if (
                not r["internal"]
                and r["third_country"]
                and r["country"] not in adequate
                and r["transfer_basis"] == "none"
            ):
                found.add((system_id, "third_country_no_safeguard", r["id"]))
            if r["agreement_required"] and r["vendor"] not in agreements:
                found.add((system_id, "missing_agreement", r["id"]))
        if (
            any(e["special_category"] for e in gt["data_elements"])
            and not q["special_category_condition"]
        ):
            found.add((system_id, "missing_art9_condition", None))
        if not q["retention"]:
            found.add((system_id, "missing_retention", None))
        if q["last_review_date"] < TWELVE_MONTHS_BEFORE:
            found.add((system_id, "stale_review", None))
    return found


def test_seeded_contradictions_are_exactly_the_derivable_problems(out: Path) -> None:
    """No seeded problem is missing from the data and no unseeded problem exists in it."""
    structural = {
        "element_not_in_policy", "undeclared_recipient", "third_country_no_safeguard",
        "missing_agreement", "missing_art9_condition", "missing_retention", "stale_review",
    }  # fmt: skip
    seeded: set[tuple[str, str, str | None]] = set()
    for c in CONTRADICTIONS:
        for kind in c["types"]:
            if kind in structural:
                subject = (
                    c["subject"]
                    if kind
                    in {
                        "element_not_in_policy",
                        "undeclared_recipient",
                        "third_country_no_safeguard",
                        "missing_agreement",
                    }
                    else None
                )
                seeded.add((c["system"], kind, subject))
    assert derived_findings(out) == seeded


def test_judgement_contradictions_are_present_in_the_files(out: Path) -> None:
    """The contradictions that need reading rather than a rule (policy claims, retention, consent)."""
    company = (DATASETS / "policies/company_privacy_policy.md").read_text(encoding="utf-8")

    # C02: the notice promises no sharing beyond payment and carrier, yet Meta receives data.
    assert "do not share your personal data with any third party other than" in policy(
        out, "web_shop"
    )
    assert any(
        urlsplit(e["request"]["url"]).netloc == "www.facebook.com"
        for e in har_entries(out, "web_shop")
    )
    # C04: company policy says 24 months, the shop keeps orders for seven years.
    assert "24 months" in company and "7 years" in questionnaire(out, "web_shop")["retention"]
    # C05: full IPv4 addresses stored although the notice claims they are shortened.
    assert "never store a full IP address" in policy(out, "web_analytics")
    db = sqlite3.connect(evidence(out, "web_analytics") / "snapshot.sqlite")
    ips = [r[0] for r in db.execute("SELECT location_ip FROM visits")]
    db.close()
    assert ips and all(re.fullmatch(r"\d+\.\d+\.\d+\.\d+", ip) for ip in ips)
    # C07: e-mail addresses stored as the user id.
    db = sqlite3.connect(evidence(out, "web_analytics") / "snapshot.sqlite")
    assert db.execute("SELECT count(*) FROM visits WHERE user_id LIKE '%@%'").fetchone()[0] > 0
    db.close()
    # C08: twelve months promised, older tickets kept.
    assert (
        "twelve months" in policy(out, "helpdesk")
        and "12 months" in questionnaire(out, "helpdesk")["retention"]
    )
    db = sqlite3.connect(evidence(out, "helpdesk") / "snapshot.sqlite")
    oldest = db.execute("SELECT min(created_at) FROM conversations").fetchone()[0]
    db.close()
    assert oldest < TWELVE_MONTHS_BEFORE
    # C09: transcripts "not stored" but messages are stored.
    assert "Chat transcripts are not stored" in policy(out, "helpdesk")
    db = sqlite3.connect(evidence(out, "helpdesk") / "snapshot.sqlite")
    assert db.execute("SELECT count(*) FROM messages").fetchone()[0] > 0
    db.close()
    # C12: legitimate interests cited for health data, health data in the snapshot.
    assert "legitimate interests" in policy(out, "clinic_portal")
    db = sqlite3.connect(evidence(out, "clinic_portal") / "snapshot.sqlite")
    assert (
        db.execute(
            "SELECT count(*) FROM consultation_notes WHERE diagnosis IS NOT NULL"
        ).fetchone()[0]
        > 0
    )
    db.close()
    # C16: consent box pre-ticked although the notice promises no ticked box.
    html = BeautifulSoup(
        (evidence(out, "newsletter") / "website_snapshot.html").read_text(encoding="utf-8"),
        "html.parser",
    )
    box = html.find("input", attrs={"name": "consent_marketing"})
    assert box is not None and box.has_attr("checked")
    assert "No box is ticked for you" in policy(out, "newsletter")
    # C19: special category columns populated in the HR snapshot.
    db = sqlite3.connect(evidence(out, "hr_onboarding") / "snapshot.sqlite")
    assert (
        db.execute("SELECT count(*) FROM onboarding_records WHERE union_member = 'yes'").fetchone()[
            0
        ]
        > 0
    )
    assert (
        db.execute(
            "SELECT count(*) FROM onboarding_records WHERE disability_status <> 'none'"
        ).fetchone()[0]
        > 0
    )
    db.close()
    # Staff desktop: Sentry is configured to send personal data.
    bundle = (evidence(out, "staff_desktop") / "main.bundle.js").read_text(encoding="utf-8")
    assert "sendDefaultPii: true" in bundle and "ingest.sentry.io" in bundle


