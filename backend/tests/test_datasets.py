@pytest.mark.parametrize("system_id", SYSTEM_IDS)
def test_ground_truth_elements_appear_in_the_evidence(out: Path, system_id: str) -> None:
    gt = truth(out, system_id)
    html = BeautifulSoup(
        (evidence(out, system_id) / "website_snapshot.html").read_text(encoding="utf-8"),
        "html.parser",
    )
    input_names = {t.get("name") for t in html.find_all(["input", "textarea", "select"])}
    db_columns = columns_of(evidence(out, system_id) / "snapshot.sqlite")
    own_host = SPEC[system_id]["host"]
    request_keys: dict[str, set[str]] = {
        "request_json_key": set(),
        "request_form_param": set(),
        "request_query_param": set(),
    }
    cookies: set[str] = set()
    third_party_params: set[tuple[str, str]] = set()
    for entry in har_entries(out, system_id):
        request = entry["request"]
        host = urlsplit(request["url"]).netloc
        if host != own_host:
            names = {q["name"] for q in request["queryString"]}
            post = request.get("postData")
            if post and "json" in post["mimeType"]:
                names |= set(flatten_json(json.loads(post["text"])))
            elif post:
                names |= {p["name"] for p in post.get("params", [])}
            third_party_params |= {(host, n) for n in names}
            continue
        post = request.get("postData")
        if post and "json" in post["mimeType"]:
            flat: set[str] = set()

            def walk(prefix: str, value: Any, sink: set[str] = flat) -> None:
                if isinstance(value, dict):
                    for k, v in value.items():
                        walk(f"{prefix}.{k}" if prefix else k, v, sink)
                else:
                    sink.add(prefix)

            walk("", json.loads(post["text"]))
            request_keys["request_json_key"] |= flat
        elif post:
            request_keys["request_form_param"] |= {p["name"] for p in post.get("params", [])}
        request_keys["request_query_param"] |= {q["name"] for q in request["queryString"]}
        cookies |= {c["name"] for c in entry["response"]["cookies"]}

    kinds_seen = set()
    for element in gt["data_elements"]:
        assert element["locations"], f"{system_id}.{element['id']} has no location"
        for location in element["locations"]:
            kind = location["kind"]
            kinds_seen.add(kind)
            if kind == "form_field":
                assert location["name"] in input_names, location
            elif kind in request_keys:
                assert location["name"] in request_keys[kind], location
            elif kind == "third_party_param":
                assert (location["host"], location["name"]) in third_party_params, location
            elif kind == "db_column":
                assert location["column"] in db_columns[location["table"]], location
            elif kind == "cookie":
                assert location["name"] in cookies, location
            else:
                pytest.fail(f"unknown location kind {kind}")
    assert kinds_seen  # at least one kind of evidence per system


