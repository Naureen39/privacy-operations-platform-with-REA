    html = (evidence(out, system_id) / "website_snapshot.html").read_text(encoding="utf-8")
    seen |= {urlsplit(u).hostname for u in re.findall(r"https?://[^\s\"'`)<]+", html)}
    seen -= {SPEC[system_id]["host"]}
    assert seen <= declared_hosts, f"hosts not in ground truth: {sorted(seen - declared_hosts)}"
    assert (
        declared_hosts - seen == set()
    ), f"ground truth hosts never seen: {sorted(declared_hosts - seen)}"


