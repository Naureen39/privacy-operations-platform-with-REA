def test_ten_request_cases_match_the_snapshots(out: Path) -> None:
    cases = jload(out / "people" / "request_cases.json")["cases"]
    assert [c["id"] for c in cases] == [f"RC{i:02d}" for i in range(1, 11)]
    with (out / "people" / "synthetic_people.csv").open(encoding="utf-8", newline="") as handle:
        by_id = {p["person_id"]: p for p in csv.DictReader(handle)}
    assert len({c["subject"]["person_id"] for c in cases}) == 10

    for case in cases:
        email = case["identifier"]["value"]
        assert email == by_id[case["subject"]["person_id"]]["email"]
        # Independent scan: every text column of every table of every snapshot.
        found: dict[tuple[str, str, str], int] = {}
        for system_id in SYSTEM_IDS:
            path = evidence(out, system_id) / "snapshot.sqlite"
            db = sqlite3.connect(f"file:{path.as_posix()}?mode=ro", uri=True)
            for table, cols in columns_of(path).items():
                for column in cols:
                    count = db.execute(
                        f'SELECT count(*) FROM "{table}" WHERE "{column}" = ?', [email]
                    ).fetchone()[0]
                    if count:
                        found[(system_id, table, column)] = count
            db.close()
        expected = {
            (loc["system"], loc["table"], loc["column"]): loc["rows"]
            for loc in case["expected_locations"]
        }
        assert found == expected, case["id"]
        assert case["expected_systems"] == sorted({k[0] for k in expected})
    by_case = {c["id"]: c for c in cases}
    assert by_case["RC10"]["expected_locations"] == []
    assert by_case["RC09"]["expected_locations"] == []  # pseudonymous visitor: no e-mail stored
    assert by_case["RC03"]["expected_systems"] == ["clinic_portal"]
    assert len(by_case["RC01"]["expected_systems"]) >= 5
    # Every case that belongs to a system is findable there (membership implies rows).
    for case in cases:
        person = by_id[case["subject"]["person_id"]]
        for system_id in case["expected_systems"]:
            assert person[SPEC[system_id]["population"]] == "1"


