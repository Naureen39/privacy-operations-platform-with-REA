def test_same_seed_gives_the_same_bytes(builds: tuple[Path, Path]) -> None:
    first, second = builds
    files_a = sorted(p.relative_to(first).as_posix() for p in first.rglob("*") if p.is_file())
    files_b = sorted(p.relative_to(second).as_posix() for p in second.rglob("*") if p.is_file())
    assert files_a == files_b and len(files_a) > 70
    assert (first / "MANIFEST.sha256").read_text() == (second / "MANIFEST.sha256").read_text()
    for name in files_a:
        assert (first / name).read_bytes() == (second / name).read_bytes(), name


def test_committed_files_match_the_manifest_and_a_fresh_build(out: Path) -> None:
    """Catches hand edits to generated files and drift between code and committed data."""
    committed = {
        line.partition("  ")[2]: line.partition("  ")[0]
        for line in (DATASETS / "MANIFEST.sha256").read_text().splitlines()
    }
    from common import sha256_file  # type: ignore[import-not-found]  # noqa: PLC0415

    for name, digest in committed.items():
        assert sha256_file(DATASETS / name) == digest, f"committed file changed: {name}"
    for name in committed:
        if name.startswith(("regulation/", "policies/company_privacy_policy.md")):
            continue  # inputs, not generated by the build
        fresh, kept = out / name, DATASETS / name
        if name.endswith(".sqlite"):
            assert sql_dump(fresh) == sql_dump(
                kept
            ), name  # compare content, not SQLite header bytes
        else:
            assert fresh.read_bytes() == kept.read_bytes(), name


