def sql_dump(path: Path) -> str:
    db = sqlite3.connect(path)
    try:
        return "\n".join(db.iterdump())
    finally:
        db.close()


def columns_of(path: Path) -> dict[str, list[str]]:
    db = sqlite3.connect(f"file:{path.as_posix()}?mode=ro", uri=True)
    try:
        tables = [
            r[0]
            for r in db.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
            )
        ]
        return {t: [r[1] for r in db.execute(f'PRAGMA table_info("{t}")')] for t in tables}
    finally:
        db.close()


def flatten_json(value: Any, prefix: str = "") -> list[str]:
    if isinstance(value, dict):
        return [
            n for k, v in value.items() for n in flatten_json(v, f"{prefix}.{k}" if prefix else k)
        ]
    return [prefix]


